function initial() {
  try {
    const asked = new URLSearchParams(location.search).get('lingua');
    if (asked === 'gl' || asked === 'es') return asked;
    const saved = localStorage.getItem(KEY);
    if (saved === 'gl' || saved === 'es') return saved;
  } catch { /* sin almacenamiento */ }
  const langs = typeof navigator !== 'undefined' ? navigator.languages ?? [navigator.language] : [];
  return langs.some((l) => /^gl\b/i.test(l ?? '')) ? 'gl' : 'es';
}

let lang = typeof location === 'undefined' ? 'es' : initial();
if (typeof document !== 'undefined') document.documentElement.lang = lang;

export const getLang = () => lang;

/** Texto en el idioma elegido, con {marcas} sustituidas. */
export function t(text, vars) {
  const out = lang === 'gl' ? (GL[text] ?? text) : text;
  return vars ? out.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`)) : out;
}

/** Traduce lo que ya está escrito en la página (marcado con data-t). */
export function translateDom(root = document) {
  root.querySelectorAll('[data-t]').forEach((el) => { el.textContent = t(el.dataset.t); });
  root.querySelectorAll('[data-t-placeholder]').forEach((el) => { el.placeholder = t(el.dataset.tPlaceholder); });
  root.querySelectorAll('[data-t-label]').forEach((el) => { el.setAttribute('aria-label', t(el.dataset.tLabel)); });
  root.querySelectorAll('[data-t-title]').forEach((el) => { el.title = t(el.dataset.tTitle); });
}

export function setLang(value) {
  lang = value === 'gl' ? 'gl' : 'es';
  try { localStorage.setItem(KEY, lang); } catch { /* solo esta visita */ }
  document.documentElement.lang = lang;
  translateDom();
}
